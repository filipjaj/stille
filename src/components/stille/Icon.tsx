export type IconProps = Omit<React.SVGProps<SVGSVGElement>, 'ref'> & {
  name?: IconName
  /** Light til kontroller, thin til store display-piler. */
  weight?: IconWeight
  size?: number
  spin?: boolean
  /** Setter role="img" og aria-label. Uten den er ikonet aria-hidden. */
  label?: string
}

export function Icon({
  name = 'arrow-right',
  weight = 'light',
  size = 22,
  spin = false,
  className,
  label,
  ...rest
}: IconProps) {
  const definition = icons[`${name}-${weight}`] ?? icons[`${name}-light`]
  if (!definition) {
    return null
  }

  const classes = ['st-icon', spin ? 'st-spin' : null, className].filter(Boolean).join(' ')

  return (
    <svg
      className={classes}
      width={size}
      height={size}
      viewBox={definition.viewBox}
      fill="currentColor"
      aria-hidden={label ? undefined : 'true'}
      role={label ? 'img' : undefined}
      aria-label={label}
      {...rest}
    >
      {definition.paths.map((d) => (
        <path key={d} d={d} />
      ))}
    </svg>
  )
}
